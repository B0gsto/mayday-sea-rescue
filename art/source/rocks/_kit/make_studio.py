"""K1 Studio pass inputs -> assets/review/K1/{shots.json, studio/*.luau}: imports the 14 kit pieces (import_asset.luau,
own Granite sets + _Wet by content hash from assets/manifest.json), then cove.luau finds a rocky shore on the real
terrain east of the harbour (raycasts: land 3 to 12 studs high with sea below -4 within 50 studs, no parts nearby),
and set-dresses a small test cove there: ledges at the waterline (ATT_Waterline at Y 0), boulders on the shore, cliff
chunks scaled x1.5 to x2.5 and stacked behind. FOV 40, four presets dry and wet + Overcast close-ups."""
import hashlib, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kit import KIT, ROOT, SET  # noqa: E402
R = ROOT + "assets/review/K1/"
man = json.load(open(ROOT + "assets/manifest.json"))
by_sha = {e.get("sha"): e for e in man.values() if isinstance(e, dict) and e.get("sha")}


def img(path):
    h = hashlib.sha256(open(ROOT + path, "rb").read()).hexdigest()
    for s, e in by_sha.items():
        if h.startswith(s) or s.startswith(h[:40]):
            return str(e.get("imageId") or e.get("assetId"))
    raise SystemExit("not uploaded: " + path)


def lua(v):
    if isinstance(v, dict):
        return "{" + ", ".join("[%s] = %s" % (json.dumps(k), lua(x)) for k, x in v.items()) + "}"
    if isinstance(v, list):
        return "{" + ", ".join(lua(x) for x in v) + "}"
    if isinstance(v, bool):
        return "true" if v else "false"
    return json.dumps(v)


cfgs = []
for asset, pid, budget, tris, tier, zone, tex in KIT:
    stem = "assets/textures/%s/T_%s_%s_" % (asset, tex, SET)
    st = {k: img(stem + k + ".png") for k in ("ALB", "NOR", "RGH", "MET")}
    st["Wet"] = {k: img(stem + k + "_Wet.png") for k in ("ALB", "RGH")}
    att = json.load(open(ROOT + "assets/fbx/%s/%s.attachments.json" % (asset, asset)))
    cfgs.append({"name": asset, "source": "Workspace/" + asset, "tier": "standard", "sets": {SET: st},
                 "partSets": {"%s_%s" % (asset, l): SET for l in ("LOD0", "LOD1", "LOD2")},
                 "attachments": [{"name": a["name"], "pos": a["roblox_from_origin"]} for a in att.get("attachments", [])],
                 "cframe": [0, 300, 0, 0]})
pre = "for _, c in workspace:GetChildren() do\n\tif c:IsA('Model') and string.match(c.Name, '^M_Rock_.*_LOD0$') then c.Name = string.gsub(c.Name, '_LOD0$', '') end\nend\n"
src = open(ROOT + "tools/studio/import_asset.luau").read()
open(R + "studio/import-setup.luau", "w").write(pre + "_G.ImportAssetConfig = " + lua(cfgs[0]) + "\n" + src)
open(R + "studio/import-rest.luau", "w").write(
    "local out = {}\nfor _, cfg in " + lua(cfgs[1:]) + " do local ok, r = pcall(_G.ImportAsset, cfg) table.insert(out, cfg.name .. (ok and ' ok' or (' ERR ' .. tostring(r)))) end\nreturn table.concat(out, '; ')\n")
# ---- the cove (offline from the real heightmap, find_cove.py -> build/k1/cove.json)
import math
import numpy as np
TG = ROOT + "map/generated/"
tm = json.load(open(TG + "terrain.json"))
TH = np.fromfile(TG + tm["height"], dtype="<i2").reshape(tm["nz"], tm["nx"]).astype(np.float32) / tm["heightScale"]


def th(x, z):
    i = int(round((z - tm["originZ"]) / tm["cell"])); j = int(round((x - tm["originX"]) / tm["cell"]))
    return float(TH[i, j])


cv = json.load(open(ROOT + "build/k1/cove.json"))
d = cv["d"]; r = [-d[1], d[0]]
W = [cv["x"], cv["z"]]
for _ in range(60):
    if th(W[0], W[1]) < 0:
        break
    W = [W[0] + d[0] * 2, W[1] + d[1] * 2]
yaw0 = math.degrees(math.atan2(-d[0], -d[1]))
wl = {}
for c in cfgs:
    a = [x for x in c["attachments"] if x["name"] == "ATT_Waterline"]
    wl[c["name"]] = a[0]["pos"][1] if a else 0.0
hgt = {a: json.load(open(ROOT + "build/k1/work/%s.json" % a))["size_studs"][2] for a, *_ in KIT}
LAYOUT = [  # asset, seaward, along shore, scale, yaw twist, mode (water: ATT_Waterline at Y 0 | ground: sink share)
    ("M_Rock_Ledge_01", 2, -16, 1.0, 90, "water"), ("M_Rock_Ledge_02", 3, 14, 1.0, 10, "water"),
    ("M_Rock_Ledge_03", 13, -1, 1.0, 40, "water"), ("M_Rock_Boulder_04", -1, 3, 1.0, 20, "water"),
    ("M_Rock_Boulder_05", -9, -7, 1.0, 60, 0.25), ("M_Rock_Boulder_06", -11, 11, 1.0, 130, 0.2),
    ("M_Rock_Boulder_01", -5, 1, 1.0, 200, 0.15), ("M_Rock_Boulder_02", -3, -5, 1.0, 75, 0.1),
    ("M_Rock_Boulder_03", -7, 7, 1.0, 300, 0.1), ("M_Rock_Cliff_01", -26, -18, 2.5, 0, 0.3),
    ("M_Rock_Cliff_03", -30, 5, 1.5, 0, 0.3), ("M_Rock_Cliff_02", -24, 26, 2.0, 180, 0.3),
    ("M_Rock_Cliff_04", -14, -36, 1.5, 0, "water"), ("M_Rock_Cliff_05", -8, 42, 1.0, 90, "water")]
place = {}
lines = ["-- K1 test cove on the real terrain (generated by make_studio.py)", "local P = {}"]
for a, sea, along, sc, tw, mode in LAYOUT:
    x = W[0] + d[0] * sea + r[0] * along; z = W[1] + d[1] * sea + r[1] * along
    y = -wl[a] * sc if mode == "water" else th(x, z) - mode * hgt[a] * sc
    place[a] = (x, y, z)
    lines.append("P[%s] = {%.2f, %.2f, %.2f, %.1f, %.2f}" % (json.dumps(a), x, y, z, yaw0 + tw, sc))
lines.append("""local n = 0
for name, p in P do
\tlocal m = workspace:FindFirstChild(name, true)
\tif m and m:IsA("Model") then
\t\tif p[5] ~= 1 then m:ScaleTo(p[5]) end
\t\tm:PivotTo(CFrame.new(p[1], p[2], p[3]) * CFrame.Angles(0, math.rad(p[4]), 0))
\t\tn += 1
\tend
end
local CP = game:GetService("ContentProvider")
local ids, seen = {}, {}
for _, dd in workspace:GetDescendants() do
\tif dd:IsA("SurfaceAppearance") and string.find(dd:GetFullName(), "M_Rock_", 1, true) then
\t\tfor _, k in { "ColorMap", "NormalMap", "RoughnessMap", "MetalnessMap" } do
\t\t\tlocal ok, v = pcall(function() return dd[k] end)
\t\t\tif ok and type(v) == "string" and v ~= "" and not seen[v] then seen[v] = true table.insert(ids, v) end
\t\tend
\tend
end
local failed = 0
for attempt = 1, 3 do
\tlocal list, bad = {}, 0
\tfor _, id in ids do local dec = Instance.new("Decal") dec.Texture = id table.insert(list, dec) end
\tpcall(function() CP:PreloadAsync(list, function(_, s) if s ~= Enum.AssetFetchStatus.Success then bad += 1 end end) end)
\tfailed = bad
\tif bad == 0 then break end
\ttask.wait(2)
end
return string.format("K1 cove: placed %d, maps %d, failed %d", n, #ids, failed)""")
open(R + "studio/cove.luau", "w").write("\n".join(lines) + "\n")


def v3(p, dsea, dal, up):
    return [round(p[0] + d[0] * dsea + r[0] * dal, 1), round(p[1] + up, 1), round(p[2] + d[1] * dsea + r[1] * dal, 1)]


Wp = (W[0], 0.0, W[1])
L1 = place["M_Rock_Ledge_01"]; B = place["M_Rock_Boulder_01"]
VIEWS = {"wide": (v3(Wp, 100, 8, 26), v3(Wp, -14, 4, 8)),
         "ledge": (v3((L1[0], 0, L1[2]), 18, 7, 5), v3((L1[0], 0, L1[2]), 0, 0, 1)),
         "boulders": (v3((B[0], B[1], B[2]), 16, -8, 8), v3((B[0], B[1], B[2]), -2, 1, 2)),
         "cliffs": (v3(Wp, 45, -4, 16), v3(Wp, -26, -2, 14))}
shots = []


def shot(name, view, preset, wet):
    cam, look = VIEWS[view]
    shots.append({"name": name, "cam": cam, "look": look, "settle": 3.0,
                  "lua": "workspace.CurrentCamera.FieldOfView = 40 _G.LookDev.shot(%s, %s) return _G.LookDev.apply('%s', %s)"
                         % (lua(cam), lua(look), preset, "true" if wet else "false")})


for p in ("Clear", "Overcast", "Storm", "Night"):
    for w in (False, True):
        shot("K1_Cove_%s_%s" % (p, "wet" if w else "dry"), "wide", p, w)
for v in ("ledge", "boulders", "cliffs"):
    for w in (False, True):
        shot("K1_%s_Overcast_%s" % (v.capitalize(), "wet" if w else "dry"), v, "Overcast", w)
json.dump(shots, open(R + "shots.json", "w"), indent=1)
print("pieces", len(cfgs), "shots", len(shots))

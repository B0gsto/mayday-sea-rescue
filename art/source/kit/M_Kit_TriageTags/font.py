GW, GH, GAP = 5, 7, 1


def width(text, scale):
    """Text width in pixels for a given scale (each glyph is 5 pixels wide plus one of gap)."""
    return max(0, (len(text) * (GW + GAP) - GAP) * scale)


def glyph_mask(text, scale):
    """The text as a boolean (rows, cols) stamp, rows top first."""
    w = width(text, scale)
    if w <= 0:
        return np.zeros((GH * scale, 1), bool)
    m = np.zeros((GH * scale, w), bool)
    col = 0
    for ch in text.upper():
        rows = GLYPHS.get(ch, GLYPHS[" "])
        for r, bits in enumerate(rows):
            for c in range(GW):
                if bits & (1 << (GW - 1 - c)):
                    m[r * scale:(r + 1) * scale, col + c * scale:col + (c + 1) * scale] = True
        col += (GW + GAP) * scale
    return m


def stamp(arr3, row, col, mask, colour):
    """Paint a glyph stamp (opaque) into an (h, w, 3) float array view at (row, col), clipped."""
    h, w = arr3.shape[:2]
    mh, mw = mask.shape
    r0, r1 = max(0, row), min(h, row + mh)
    c0, c1 = max(0, col), min(w, col + mw)
    if r1 <= r0 or c1 <= c0:
        return
    sub = mask[r0 - row:r1 - row, c0 - col:c1 - col]
    arr3[r0:r1, c0:c1][sub] = np.asarray(colour, np.float32)


def draw(arr3, row, col, text, scale, colour, tracking=0):
    """Draw `text` with its top-left at pixel (row, col)."""
    col += 0
    for ch in text.upper():
        if ch != " ":
            stamp(arr3, row, col, glyph_mask(ch, scale), colour)
        col += (GW + GAP + tracking) * scale
